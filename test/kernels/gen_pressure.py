#!/usr/bin/env python3
"""Generates pressure_loop.ptx: N independent f32 accumulators kept live across a loop.

Usage: python gen_pressure.py [N=48] > pressure_loop.ptx
With N accumulators the peak register demand is roughly N + address/loop registers, so the kernel
spills under --maxrregcount=32 and is a good end-to-end test for the allocator.
"""
import sys

n = int(sys.argv[1]) if len(sys.argv) > 1 else 48
out = []
w = out.append
w("// Generated by gen_pressure.py: %d loop-carried f32 accumulators" % n)
w(".version 8.0\n.target sm_80\n.address_size 64\n")
w(".visible .entry pressure_loop(")
w("\t.param .u64 pressure_loop_param_0,")
w("\t.param .u64 pressure_loop_param_1,")
w("\t.param .u32 pressure_loop_param_2")
w(")\n{")
w("\t.reg .pred \t%%p<3>;\n\t.reg .b32 \t%%r<6>;\n\t.reg .f32 \t%%f<%d>;\n\t.reg .b64 \t%%rd<8>;" % (n + 3))
w("\tld.param.u64 \t%rd1, [pressure_loop_param_0];")
w("\tld.param.u64 \t%rd2, [pressure_loop_param_1];")
w("\tld.param.u32 \t%r1, [pressure_loop_param_2];")
w("\tcvta.to.global.u64 \t%rd3, %rd1;")
w("\tcvta.to.global.u64 \t%rd4, %rd2;")
w("\tmov.u32 \t%r2, %tid.x;")
w("\tmul.wide.s32 \t%rd5, %r2, 4;")
w("\tadd.s64 \t%rd6, %rd3, %rd5;")
for i in range(n):
    w("\tld.global.f32 \t%%f%d, [%%rd6+%d];" % (i + 1, i * 4))
w("\tmov.u32 \t%r3, 0;")
w("\tsetp.ge.s32 \t%p1, %r3, %r1;")
w("\t@%p1 bra \t$L__BB0_3;")
w("$L__BB0_2:")
for i in range(n):
    nxt = (i + 1) % n + 1
    w("\tfma.rn.f32 \t%%f%d, %%f%d, %%f%d, %%f%d;" % (i + 1, i + 1, nxt, i + 1))
w("\tadd.s32 \t%r3, %r3, 1;")
w("\tsetp.lt.s32 \t%p2, %r3, %r1;")
w("\t@%p2 bra \t$L__BB0_2;")
w("$L__BB0_3:")
total = n + 1
w("\tmov.f32 \t%%f%d, 0f00000000;" % total)
for i in range(n):
    w("\tadd.f32 \t%%f%d, %%f%d, %%f%d;" % (total, total, i + 1))
w("\tadd.s64 \t%rd7, %rd4, %rd5;")
w("\tst.global.f32 \t[%%rd7], %%f%d;" % total)
w("\tret;\n}")
print("\n".join(out))
